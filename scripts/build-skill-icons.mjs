#!/usr/bin/env node
/**
 * Extracts just the icons the skills use from the CC0 `simple-icons` package into
 * lib/skillIcons.generated.ts, so the site ships a few KB of SVG paths, not the library.
 *
 *   pnpm icons
 *
 * Skills with no official icon (AWS, Azure, OpenShift, SQL, WebSocket) get a drawn badge in
 * components/ui/SkillIcon.tsx. Add a skill here when you add it in /admin.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import * as si from "simple-icons";

const ROOT = path.resolve(import.meta.dirname, "..");

/** normalised skill name → Simple Icons slug */
const MAP = {
  python: "python",
  java: "openjdk",
  javascript: "javascript",
  php: "php",
  html: "html5",
  css: "css",
  lua: "lua",
  fastapi: "fastapi",
  flask: "flask",
  "react.js": "react",
  react: "react",
  "vue.js": "vuedotjs",
  vue: "vuedotjs",
  "node.js": "nodedotjs",
  node: "nodedotjs",
  "tailwind css": "tailwindcss",
  bootstrap: "bootstrap",
  pandas: "pandas",
  docker: "docker",
  kubernetes: "kubernetes",
  argocd: "argo",
  rabbitmq: "rabbitmq",
  redis: "redis",
  "kong api gateway": "kong",
  kong: "kong",
  prometheus: "prometheus",
  grafana: "grafana",
  "google cloud": "googlecloud",
};

const bySlug = new Map(
  Object.values(si)
    .filter((i) => i && i.slug)
    .map((i) => [i.slug, i]),
);
const out = {};
const missing = [];
for (const [name, slug] of Object.entries(MAP)) {
  const icon = bySlug.get(slug);
  if (!icon) {
    missing.push(`${name} (${slug})`);
    continue;
  }
  out[name] = { path: icon.path, hex: icon.hex };
}

const file = `// GENERATED by scripts/build-skill-icons.mjs from simple-icons (CC0). Do not edit by hand.
export interface SkillIconData {
  /** SVG path for a 24×24 viewBox. */
  path: string;
  /** Brand colour, hex without #. */
  hex: string;
}

export const SKILL_ICONS: Record<string, SkillIconData> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(path.join(ROOT, "lib", "skillIcons.generated.ts"), file);
console.log(
  `wrote ${Object.keys(out).length} icons${missing.length ? `; missing: ${missing.join(", ")}` : ""}`,
);
